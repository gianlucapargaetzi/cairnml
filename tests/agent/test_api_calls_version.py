"""The API version a call goes out at, and what the agent's feature checks ask about the definition a call uses.

Every request goes out at the negotiated level (the SDK's request_version). A feature is available when the definition
the call is sent with declares what the feature sends, or when the action is served at all; the tests fix those
answers at a few server levels.
"""

import ast
import re
from pathlib import Path
from types import SimpleNamespace

import pytest
from cairnml.backend_api.services import API_LEVEL

from cairnml_agent.session import Session


@pytest.fixture
def server_level(monkeypatch):
    """The server reports the level the test names; the SDK's negotiated level follows it."""

    def set_level(level):
        monkeypatch.setattr(Session, "max_api_version", level)

    return set_level


def test_a_request_goes_out_at_the_servers_level_when_it_is_older_than_the_client(server_level):
    server_level("2.9")
    assert Session.request_version("tasks", "get_all") == "2.9"


def test_a_request_goes_out_at_the_clients_level_when_the_server_is_newer(server_level):
    server_level("9.9")
    assert Session.request_version("tasks", "get_all") == API_LEVEL


def test_an_action_is_served_from_the_level_of_its_first_definition(server_level):
    server_level("2.8")
    assert not Session.serves("debug", "ping")
    server_level("2.9")
    assert Session.serves("debug", "ping")


def test_the_container_of_a_task_is_declared_from_the_definition_that_added_it(server_level):
    server_level("2.12")
    assert not Session.declares("tasks", "edit", "container")
    server_level("2.13")
    assert Session.declares("tasks", "edit", "container")


def test_search_hidden_is_declared_from_the_definition_that_added_it(server_level):
    server_level("2.13")
    assert not Session.declares("tasks", "get_all", "search_hidden")
    server_level("2.14")
    assert Session.declares("tasks", "get_all", "search_hidden")


def test_an_action_that_is_not_served_declares_nothing(server_level):
    server_level("2.8")
    assert not Session.declares("debug", "ping", "anything")


def test_the_definition_is_the_newest_one_at_or_below_the_level(server_level):
    server_level("2.14")
    request_cls, response_cls = Session.definition("tasks", "get_all")
    assert request_cls._version == "2.14"
    assert response_cls is not None


def test_a_call_to_an_older_server_is_sent_at_the_servers_level_with_the_older_definition(server_level, monkeypatch):
    """The container edit of a server without the container field goes out at the server's level, with the
    definition of that level (execution, not container)."""
    from cairnml_agent.commands.worker import set_task_container

    from .wire import WireSession, answer

    server_level("2.9")
    session = WireSession({"tasks.edit": answer({"updated": 1})}, config={})
    assert set_task_container(session, "task-1", "ubuntu", ["-v", "/a:/b"], "ls")
    [call] = session.of("tasks.edit")
    assert call.version == "2.9"
    assert call.json["execution"] == {"docker_cmd": "ubuntu -v /a:/b"}
    assert "container" not in call.json


def test_the_commit_of_a_task_is_written_with_the_definition_the_server_serves(server_level):
    from cairnml_agent.commands.worker import Worker

    from .wire import WireSession, answer

    server_level("2.9")
    session = WireSession({"tasks.edit": answer({"updated": 1})}, config={})
    repo_info = SimpleNamespace(commit="abc123")
    execution = SimpleNamespace(version_num=None)
    Worker._update_commit_id(SimpleNamespace(_session=session, log=lambda *args: None), "task-1", execution, repo_info)
    [call] = session.of("tasks.edit")
    assert call.version == "2.9"
    assert call.json["script"]["version_num"] == "abc123"


AGENT = Path(__file__).resolve().parents[2] / "cairnml_agent"
VERSION_TEXT = re.compile(r"^\d+\.\d+$|^v\d+\.\d+$")


def _agent_modules():
    """The hand-written modules of the agent: the generated ones are not judged."""
    for path in sorted(AGENT.rglob("*.py")):
        text = path.read_text(encoding="utf-8")
        if "# Generated by apiserver.client_generator" in text:
            continue
        yield path, ast.parse(text, filename=str(path))


def test_no_version_literal_is_passed_to_a_call_or_a_feature_check():
    """A version a call goes out at comes from the SDK's negotiated level (request_version), and a feature check asks
    the definition (serves, declares), so no literal API version names a call or a gate in the agent."""
    found = []
    for path, tree in _agent_modules():
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            for keyword in node.keywords:
                is_text = isinstance(keyword.value, ast.Constant) and isinstance(keyword.value.value, str)
                if keyword.arg == "version" and is_text:
                    found.append(f"{path.name}:{node.lineno} version={keyword.value.value!r}")
            if isinstance(node.func, ast.Attribute) and node.func.attr == "check_min_api_version":
                found.append(f"{path.name}:{node.lineno} check_min_api_version")
            for arg in node.args:
                if isinstance(arg, ast.Constant) and isinstance(arg.value, str) and VERSION_TEXT.match(arg.value):
                    found.append(f"{path.name}:{node.lineno} {arg.value!r} passed as an argument")
    assert found == []


def _names_by_string(call):
    """Whether a session call names its service and action by string constants: `send_request` by its first two
    arguments or by keyword, `get` and `post` by the keywords `service` and `action` (other calls, such as
    `dict.get("key", "default")`, are not API calls)."""
    keywords = {k.arg: k.value for k in call.keywords if k.arg}
    constant = lambda node: isinstance(node, ast.Constant) and isinstance(node.value, str)
    if call.func.attr == "send_request":
        service = keywords.get("service", call.args[0] if len(call.args) > 0 else None)
        action = keywords.get("action", call.args[1] if len(call.args) > 1 else None)
        return constant(service) and constant(action)
    return constant(keywords.get("service")) and constant(keywords.get("action"))


def test_no_call_names_its_service_and_action_by_strings():
    """A call that sends is built from a generated request class (cairnml.backend_api.services.<service>.<Action>Request,
    at the level the session negotiated), so the agent names no service and action by strings."""
    found = []
    for path, tree in _agent_modules():
        for fn in ast.walk(tree):
            if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for node in ast.walk(fn):
                if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
                    continue
                if node.func.attr in ("send_request", "get", "post") and _names_by_string(node):
                    found.append(f"{path.name}:{node.lineno} in {fn.name}")
    assert found == []


def test_no_hand_built_request_body():
    """A body is not written as a dict literal next to the call that sends it: the request is a generated class."""
    offenders = []
    for path, tree in _agent_modules():
        for fn in ast.walk(tree):
            if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for node in ast.walk(fn):
                if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
                    continue
                if node.func.attr not in ("send_request", "get", "post", "send_api", "send"):
                    continue
                bodies = [k.value for k in node.keywords if k.arg in ("json", "data")]
                literal = any(isinstance(value, ast.Dict) for value in bodies)
                literal = literal or (
                    node.func.attr in ("send_api", "send") and bool(node.args) and isinstance(node.args[0], ast.Dict)
                )
                if literal:
                    offenders.append(f"{path.name}:{node.lineno} in {fn.name}")
    assert offenders == []
